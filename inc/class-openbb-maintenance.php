class OPENBB_Maintenance {

	const TEST_MODE_OPTION  = 'openbb_test_mode';
	const DEMO_USER_OPTION  = 'openbb_demo_user_id';
	const DEMO_CYCLE_NAME   = '[DEMO] Open Bulk Buying sample cycle';
	const DEMO_PRODUCT_SLUG = 'openbb-demo-product';
	const DEMO_STOCK_KEY    = 'openbb-demo-stock-v1';

	public static function is_test_mode(): bool {
		return (bool) get_option( self::TEST_MODE_OPTION, false );
	}

	/**
	 * Creates one repeatable, clearly marked product, cycle, draft order and stock receipt.
	 *
	 * @return true|WP_Error
	 */
	public static function populate_test_data() {
		global $wpdb;

		if ( ! self::is_test_mode() ) {
			return new WP_Error( 'openbb_test_mode_disabled', __( 'Enable test mode before populating demo data.', 'open-bulk-buying' ) );
		}

		$product_post = get_page_by_path( self::DEMO_PRODUCT_SLUG, OBJECT, OPENBB_PRODUCT_POST_TYPE );
		if ( $product_post ) {
			if ( '1' !== get_post_meta( $product_post->ID, '_openbb_demo_data', true ) ) {
				return new WP_Error( 'openbb_demo_product_conflict', __( 'A non-demo product is already using the demo product identifier.', 'open-bulk-buying' ) );
			}
			$product_id = (int) $product_post->ID;
		} else {
			$product_id = wp_insert_post(
				array(
					'post_type'   => OPENBB_PRODUCT_POST_TYPE,
					'post_status' => 'publish',
					'post_title'  => __( '[DEMO] Sample bulk beans', 'open-bulk-buying' ),
					'post_name'   => self::DEMO_PRODUCT_SLUG,
				),
				true
			);
			if ( is_wp_error( $product_id ) ) {
				return $product_id;
			}
			update_post_meta( $product_id, '_openbb_demo_data', '1' );
		}

		$product_meta = array(
			'name'             => array( 'default' => __( '[DEMO] Sample bulk beans', 'open-bulk-buying' ) ),
			'description'      => array( 'default' => __( 'Test data generated by Open Bulk Buying.', 'open-bulk-buying' ) ),
			'brand'            => __( 'Demo supplier', 'open-bulk-buying' ),
			'unit_amount'      => 1,
			'unit_type'        => OPENBB_UNIT_TYPE_DEFAULT,
			'price'            => 250,
			'container_charge' => 0,
			'active'           => true,
		);
		$expected_product = new OPENBB_Product( $product_meta );
		$existing_product = OPENBB_Product::get( $product_id );
		if ( ! $existing_product ) {
			return new WP_Error( 'openbb_demo_product_failed', __( 'The demo product could not be loaded.', 'open-bulk-buying' ) );
		}
		foreach ( $product_meta as $field => $value ) {
			if ( $existing_product->{$field} !== $expected_product->{$field}
				&& false === update_post_meta( $product_id, OPENBB_META_PREFIX . $field, $value ) ) {
				return new WP_Error( 'openbb_demo_product_failed', __( 'The demo product could not be populated.', 'open-bulk-buying' ) );
			}
		}

		$cycle = self::get_demo_cycle();
		if ( ! $cycle ) {
			$cycle = new OPENBB_Cycle(
				array(
					'name'   => self::DEMO_CYCLE_NAME,
					'status' => OPENBB_Cycle::STATUS_SETUP,
				)
			);
			if ( ! $cycle->save() ) {
				return new WP_Error( 'openbb_demo_cycle_failed', __( 'The demo cycle could not be populated.', 'open-bulk-buying' ) );
			}
		}

		$user_id = absint( get_option( self::DEMO_USER_OPTION, 0 ) );
		if ( ! $user_id || ! get_userdata( $user_id ) ) {
			$user_id = get_current_user_id();
			if ( ! $user_id ) {
				return new WP_Error( 'openbb_demo_user_missing', __( 'A WordPress user is needed to create the demo order.', 'open-bulk-buying' ) );
			}
			update_option( self::DEMO_USER_OPTION, $user_id, false );
		}
		$order   = OPENBB_Orders::get_for_member( $cycle->id, $user_id );
		if ( ! $order ) {
			$order = new OPENBB_Order(
				array(
					'cycle_id' => $cycle->id,
					'user_id'  => $user_id,
					'status'   => OPENBB_Order::STATUS_DRAFT,
					'currency' => openbb_currency(),
				)
			);
			if ( ! $order->save() ) {
				return new WP_Error( 'openbb_demo_order_failed', __( 'The demo order could not be populated.', 'open-bulk-buying' ) );
			}
		}

		if ( ! $order->get_lines() ) {
			$product = OPENBB_Product::get( $product_id );
			$line    = new OPENBB_Order_Line(
				array(
					'order_id'      => $order->id,
					'product_id'    => $product_id,
					'source'        => OPENBB_Order_Line::SOURCE_MEMBER,
					'product_name'  => $product ? $product->get_name() : __( '[DEMO] Sample bulk beans', 'open-bulk-buying' ),
					'brand'         => __( 'Demo supplier', 'open-bulk-buying' ),
					'unit_amount'   => 1,
					'unit_type'     => OPENBB_UNIT_TYPE_DEFAULT,
					'base_per_unit' => $product ? $product->get_base_per_unit() : 1,
					'unit_price'    => 250,
					'qty_requested' => 2,
				)
			);
			if ( ! $line->save() ) {
				return new WP_Error( 'openbb_demo_order_line_failed', __( 'The demo order line could not be populated.', 'open-bulk-buying' ) );
			}
		}

		$stock_move_id = $wpdb->get_var( $wpdb->prepare( "SELECT id FROM {$wpdb->openbb_stock_moves} WHERE request_key = %s", self::DEMO_STOCK_KEY ) );
		if ( ! $stock_move_id ) {
			$move = new OPENBB_Stock_Move(
				array(
					'product_id'  => $product_id,
					'quantity'    => 10,
					'reason'      => OPENBB_Stock_Move::REASON_RECEIPT,
					'user_id'     => $user_id,
					'request_key' => self::DEMO_STOCK_KEY,
					'note'        => __( 'Generated demo stock receipt.', 'open-bulk-buying' ),
				)
			);
			if ( ! $move->save() ) {
				return new WP_Error( 'openbb_demo_stock_failed', __( 'The demo stock receipt could not be populated.', 'open-bulk-buying' ) );
			}
		}

		return true;
	}

	/**
	 * Deletes plugin-owned data on the current site, but preserves WordPress accounts,
	 * WordPress roles, other sites on the network, and the database schema/version.
	 *
	 * @return true|WP_Error
	 */
	public static function delete_all_site_data() {
		global $wpdb;

		if ( false === $wpdb->query( 'START TRANSACTION' ) ) {
			return new WP_Error( 'openbb_delete_all_failed', __( 'Open Bulk Buying data could not be deleted.', 'open-bulk-buying' ) );
		}

		$tables = array(
			$wpdb->openbb_order_events,
			$wpdb->openbb_order_lines,
			$wpdb->openbb_orders,
			$wpdb->openbb_stock_moves,
			$wpdb->openbb_cycles,
			$wpdb->openbb_rules_versions,
		);
		foreach ( $tables as $table ) {
			if ( false === $wpdb->query( "DELETE FROM {$table}" ) ) {
				$wpdb->query( 'ROLLBACK' );
				return new WP_Error( 'openbb_delete_all_failed', __( 'Open Bulk Buying data could not be deleted.', 'open-bulk-buying' ) );
			}
		}
		if ( false === $wpdb->query( 'COMMIT' ) ) {
			$wpdb->query( 'ROLLBACK' );
			return new WP_Error( 'openbb_delete_all_failed', __( 'Open Bulk Buying data could not be deleted.', 'open-bulk-buying' ) );
		}

		$product_ids = get_posts(
			array(
				'post_type'      => OPENBB_PRODUCT_POST_TYPE,
				'post_status'    => get_post_stati( array(), 'names' ),
				'posts_per_page' => -1,
				'fields'         => 'ids',
			)
		);
		foreach ( $product_ids as $product_id ) {
			if ( ! wp_delete_post( (int) $product_id, true ) ) {
				return new WP_Error( 'openbb_delete_all_failed', __( 'Some product data could not be deleted.', 'open-bulk-buying' ) );
			}
		}

		foreach ( array( OPENBB_PRODUCT_TAXONOMY, OPENBB_SUPPLIER_TAXONOMY ) as $taxonomy ) {
			$terms = get_terms(
				array(
					'taxonomy'   => $taxonomy,
					'hide_empty' => false,
				)
			);
			if ( is_wp_error( $terms ) ) {
				return $terms;
			}
			foreach ( $terms as $term ) {
				$deleted = wp_delete_term( (int) $term->term_id, $taxonomy );
				if ( is_wp_error( $deleted ) || ! $deleted ) {
					return new WP_Error( 'openbb_delete_all_failed', __( 'Some product taxonomy data could not be deleted.', 'open-bulk-buying' ) );
				}
			}
		}

		$meta_prefix = $wpdb->get_blog_prefix() . OPENBB_META_PREFIX;
		$meta_keys   = $wpdb->get_col(
			$wpdb->prepare(
				"SELECT DISTINCT meta_key FROM {$wpdb->usermeta} WHERE meta_key LIKE %s",
				$wpdb->esc_like( $meta_prefix ) . '%'
			)
		);
		foreach ( $meta_keys as $meta_key ) {
			delete_metadata( 'user', 0, $meta_key, '', true );
		}

		$options = $wpdb->get_col(
			$wpdb->prepare(
				"SELECT option_name FROM {$wpdb->options} WHERE option_name LIKE %s AND option_name != %s",
				$wpdb->esc_like( 'openbb_' ) . '%',
				OPENBB_Installer::DB_VERSION_OPTION
			)
		);
		foreach ( $options as $option ) {
			delete_option( $option );
		}

		return true;
	}

	private static function get_demo_cycle(): ?OPENBB_Cycle {
		global $wpdb;

		$id = $wpdb->get_var( $wpdb->prepare( "SELECT id FROM {$wpdb->openbb_cycles} WHERE name = %s", self::DEMO_CYCLE_NAME ) );

		return $id ? OPENBB_Cycles::get( (int) $id ) : null;
	}
}
